function spec = tsfsb_benchmark_spec()
%TSFSB_BENCHMARK_SPEC Fixed scope and plotting options for the TSFSB benchmark.
%
%   Ported from the C02 c02_benchmark_spec.m (commit 846d5c5f) with the
%   ten-solver pool, no exclusion list, and no fixed problem count. The
%   problem count is never hardcoded here; it comes from the frozen
%   problem manifest built by tsfsb_build_problem_manifest.

[pool, subsets] = tsfsb_solver_pool();
feature_names = { ...
    'plain', ...
    'noisy_1e-1', ...
    'noisy_1e-2', ...
    'noisy_1e-3', ...
    'noisy_1e-4', ...
    'linearly_transformed', ...
    'linearly_transformed_noisy_1e-1', ...
    'linearly_transformed_noisy_1e-2', ...
    'linearly_transformed_noisy_1e-3', ...
    'linearly_transformed_noisy_1e-4'};

features = repmat(struct( ...
    'name', '', ...
    'noise_level', 0, ...
    'orthogonally_transformed', false, ...
    'n_runs', 5), 1, numel(feature_names));
for i = 1:numel(feature_names)
    name = feature_names{i};
    features(i).name = name;
    features(i).orthogonally_transformed = ...
        startsWith(name, 'linearly_transformed');
    if contains(name, 'noisy')
        exponent_text = extractAfter(name, '1e-');
        features(i).noise_level = 10^(-str2double(exponent_text));
    end
end
features(1).n_runs = 1;

spec = struct();
spec.schema_version = 1;
spec.problem_library = 's2mpj';
spec.problem_type = 'u';
spec.minimum_dimension = 6;
spec.maximum_dimension = 50;
spec.budget_factor = 500;
spec.worker_count = 30;
spec.base_seed = 20260828;
spec.run_identifiers = 1:5;
spec.maximum_tolerance_order = 4;
spec.displayed_tolerance_orders = [2, 4];
spec.features = features;
spec.pool = pool;
spec.subsets = subsets;
spec.problem_manifest = getenv('TSFSB_PROBLEM_MANIFEST');
if isempty(spec.problem_manifest)
    spec.problem_manifest = fullfile( ...
        fileparts(mfilename('fullpath')), 'problem_manifest.mat');
end
% Ten distinct RGB rows: the first seven are the MATLAB colororder
% defaults, followed by black, magenta, and teal.
spec.line_colors = [ ...
    0.0000, 0.4470, 0.7410; ...
    0.8500, 0.3250, 0.0980; ...
    0.9290, 0.6940, 0.1250; ...
    0.4940, 0.1840, 0.5560; ...
    0.4660, 0.6740, 0.1880; ...
    0.3010, 0.7450, 0.9330; ...
    0.6350, 0.0780, 0.1840; ...
    0.0000, 0.0000, 0.0000; ...
    0.7500, 0.0000, 0.7500; ...
    0.0000, 0.5000, 0.5000];
% Line styles from the OptiProfiler whitelist (line styles only, no
% markers; see checkValidityProfileOptions.m).
spec.line_styles = {'-', '--', '-.', ':', '-', '--', '-.', ':', '-', '--'};
spec.line_widths = 1.5 * ones(1, 10);

end
